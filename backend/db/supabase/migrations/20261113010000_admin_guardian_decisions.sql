create or replace function admin.on_verdict() returns trigger
language plpgsql security definer set search_path = admin, pg_temp set lock_timeout = '200ms' as $$
declare
  v_ref  text;
  v_by   text;
  v_scam boolean;
  v_last admin.domain_labels;
  v_scan text;
  v_note text;
  v_label_id bigint;
begin
  begin
    v_ref := admin.owner_ref(new.owner_id);
    v_by  := admin.owner_ref(new.by_device_id);
    v_note := admin.mask_note(new.notes);
  exception when others then
    raise warning 'admin_trigger_failed on_verdict % %', sqlstate, sqlerrm;
    return null;
  end;
  -- Its own block: a failed archive lookup leaves scan_id null, never loses the label.
  begin
    v_scan := coalesce(new.scan_id,
                (select l.scan_id from admin.scan_archive l
                  where l.owner_ref = v_ref and l.domain = new.domain and l.detected_at <= new.decided_at
                  order by l.detected_at desc limit 1));
  exception when others then
    raise warning 'admin_trigger_failed on_verdict_scan % %', sqlstate, sqlerrm;
    v_scan := new.scan_id;
  end;
  <<label>>
  begin
    v_scam := new.value = 'not_safe';
    select * into v_last from admin.domain_labels l
     where l.owner_ref = v_ref and l.domain = new.domain and l.source = 'guardian'
       and not admin._forgotten(l.owner_ref, l.by_ref, l.created_at)
     order by l.id desc limit 1;
    if found and (v_last.analyzed_at is null or v_last.is_scam = v_scam) then
      exit label;   -- locked (Q33), or the same decision again (upsert with the same value)
    end if;
    insert into admin.domain_labels (domain, is_scam, source, connected, ai_score, ai_status,
                                     thresholds_version, owner_ref, by_ref, revision_of, scan_id, note)
    select new.domain, v_scam, 'guardian',
           new.owner_id = new.by_device_id
             or exists (select 1 from public.family_links f
                         where f.protected_id = new.owner_id and f.guardian_id = new.by_device_id),
           s.score, s.status::text, (select version from admin.public_config), v_ref, v_by, v_last.id, v_scan,
           v_note
    from (select 1) one
    left join public.scans s on s.id = new.scan_id
    returning id into v_label_id;
  exception when others then
    raise warning 'admin_trigger_failed on_verdict % %', sqlstate, sqlerrm;
  end;
  -- QA-D-H01: every decision, also when the label slot is locked or per link (D-dash-20).
  begin
    if tg_op = 'INSERT' or old.value is distinct from new.value
       or old.by_device_id is distinct from new.by_device_id then
      insert into admin.guardian_decisions (label_id, scan_id, domain, owner_ref, by_ref, is_scam, note,
                                            connected, thresholds_version, ai_score, ai_status)
      select v_label_id, v_scan, new.domain, v_ref, v_by, new.value = 'not_safe', v_note,
             new.owner_id = new.by_device_id
               or exists (select 1 from public.family_links f
                           where f.protected_id = new.owner_id and f.guardian_id = new.by_device_id),
             (select version from admin.public_config), s.score, s.status::text
      from (select 1) one
      left join public.scans s on s.id = new.scan_id;
    end if;
  exception when others then
    raise warning 'admin_trigger_failed on_verdict_decision % %', sqlstate, sqlerrm;
  end;
  begin
    update admin.scan_archive a set verdict = new.value::text, verdict_at = new.decided_at, by_ref = v_by,
                                    note = v_note
     where a.scan_id = v_scan;
  exception when others then
    raise warning 'admin_trigger_failed on_verdict_archive % %', sqlstate, sqlerrm;
  end;
  return null;
end $$;

create or replace trigger admin_verdict_label after insert or update of value, by_device_id on public.verdicts
  for each row execute function admin.on_verdict();

-- ---------------------------------------------------------------- forget (K11, K12, I11)

-- Device delete (by_ref null in label_forget terms) or family unlink. A held row or any other failed
-- delete queues the forget entry; ai_dataset hides queued rows at once and on_forget_drain deletes them.
create function admin.on_decision_forget() returns trigger
language plpgsql security definer set search_path = admin, pg_temp set lock_timeout = '200ms' as $$
declare
  v_owner text;
  v_by    text;
begin
  begin
    if tg_table_name = 'devices' then
      v_owner := admin.owner_ref(old.id);
    else
      v_owner := admin.owner_ref(old.protected_id);
      v_by    := admin.owner_ref(old.guardian_id);
    end if;
    begin
      delete from admin.guardian_decisions g
       where (v_by is null and (g.owner_ref = v_owner or g.by_ref = v_owner))
          or (g.owner_ref = v_owner and g.by_ref = v_by);
    exception when others then
      -- Held row (lock_not_available) or any other failure: queue the forget entry, which hides the
      -- rows in ai_dataset at once and lets on_forget_drain retry (fail closed, not open).
      raise warning 'admin_trigger_queued on_decision_forget % %', sqlstate, sqlerrm;
      insert into admin.label_forget (owner_ref, by_ref) values (v_owner, v_by);
    end;
  exception when others then
    raise warning 'admin_trigger_failed on_decision_forget % %', sqlstate, sqlerrm;
  end;
  return null;
end $$;
revoke all on function admin.on_decision_forget()
  from public, anon, authenticated, service_role, shoo_api, shoo_admin, shoo_ai;

create trigger admin_device_forget_decisions after delete on public.devices
  for each row execute function admin.on_decision_forget();
create trigger admin_family_unlink_decisions after delete on public.family_links
  for each row execute function admin.on_decision_forget();

create or replace function admin.on_forget_drain() returns trigger
language plpgsql security definer set search_path = admin, pg_temp as $$
begin
  delete from admin.guardian_decisions g
   where g.created_at <= old.at
     and ((old.by_ref is null and (g.owner_ref = old.owner_ref or g.by_ref = old.owner_ref))
          or (g.owner_ref = old.owner_ref and g.by_ref = old.by_ref));
  perform admin._archive_forget(old.owner_ref, old.by_ref, old.at);
  return old;
exception when lock_not_available then
  return null;
end $$;

