-- QA-D-H01 (dashboard fase 13): one dataset row per Guardian decision (D-dash-20).
--
-- Since per-link verdicts (#241), one owner can decide several links of one domain. admin.on_verdict
-- keeps one learning label per owner + domain (Q33: locked until the next analysis; a changed decision
-- after that is a revision row). Per-link decisions in between left no trace: admin.ai_dataset read
-- admin.domain_labels, so two links decided on one domain gave one dataset row.
--
--   * admin.guardian_decisions: append-only, one row per verdict insert and per change of value or
--     Guardian (by_device_id). Never read by run_analysis or the label views: Q33 votes and the six
--     readers of domain_labels stay as they are. label_id points at the label the decision made, or
--     is null when the label slot was locked or already held the same decision.
--   * admin.on_verdict also writes the decision, in its own block (a failed decision never loses the
--     label). The trigger now also fires on a by_device_id change.
--   * Forget (K11, K12, I11): a device delete or family unlink deletes its decisions at once; a held
--     row queues admin.label_forget, which hides it in ai_dataset and is drained by on_forget_drain.
--   * admin.ai_dataset reads guardian_decisions. Columns unchanged.
--   * Backfill: every guardian label becomes a decision with the same id (label_id = id); then each
--     verdict decided after the per-link merge (2026-11-08 16:13:18 UTC, Final-CH7 #336) that no label
--     represents (same owner, Guardian, domain, value and the same scan or link) adds one row, unless
--     its pair has unlinked since or the forget queue holds it.
--
-- Rollback (one transaction):
--   drop trigger admin_device_forget_decisions on public.devices;
--   drop trigger admin_family_unlink_decisions on public.family_links;
--   drop function admin.on_decision_forget(), admin._guardian_decisions_backfill(timestamptz);
--   re-run admin.ai_dataset from 20261107095337_admin_domain_lists.sql, admin.on_verdict from
--   20261108100000_verdicts_per_link.sql, admin.on_forget_drain from 20261104085245_admin_scan_archive.sql;
--   create or replace trigger admin_verdict_label after insert or update of value on public.verdicts
--     for each row execute function admin.on_verdict();
--   drop table admin.guardian_decisions;

set local lock_timeout = '1s';
set local statement_timeout = '60s';

-- No verdict may land between the backfill and the new trigger.
lock table public.verdicts in share row exclusive mode;

create table admin.guardian_decisions (
  id                 bigint generated by default as identity primary key,
  label_id           bigint,
  scan_id            text check (char_length(scan_id) between 1 and 64),
  domain             text not null check (domain = lower(domain) and domain !~ '^www\.'),
  owner_ref          text not null check (owner_ref ~ '^[0-9a-f]{16}$'),
  by_ref             text not null check (by_ref ~ '^[0-9a-f]{16}$'),
  is_scam            boolean not null,
  note               text check (char_length(note) <= 1000),
  connected          boolean not null,
  thresholds_version int,
  ai_score           int check (ai_score between 0 and 100),
  ai_status          text check (ai_status in ('warning', 'blocked')),
  created_at         timestamptz not null default clock_timestamp()
);
create index guardian_decisions_owner on admin.guardian_decisions (owner_ref);
create index guardian_decisions_by on admin.guardian_decisions (by_ref);
alter table admin.guardian_decisions enable row level security;
revoke all on admin.guardian_decisions from public, anon, authenticated, service_role, shoo_api, shoo_admin, shoo_ai;
revoke all on sequence admin.guardian_decisions_id_seq
  from public, anon, authenticated, service_role, shoo_api, shoo_admin, shoo_ai;

-- ---------------------------------------------------------------- backfill

create function admin._guardian_decisions_backfill(p_cutoff timestamptz) returns void
language plpgsql set search_path = admin, pg_temp as $$
declare
  v_max bigint;
begin
  insert into admin.guardian_decisions (id, label_id, scan_id, domain, owner_ref, by_ref, is_scam, note,
                                        connected, thresholds_version, ai_score, ai_status, created_at)
  select l.id, l.id, l.scan_id, l.domain, l.owner_ref, l.by_ref, l.is_scam, l.note,
         l.connected, l.thresholds_version, l.ai_score, l.ai_status, l.created_at
    from admin.domain_labels l
   where l.source = 'guardian'
  on conflict (id) do nothing;

  select greatest(coalesce((select max(id) from admin.domain_labels), 0),
                  coalesce((select max(id) from admin.guardian_decisions), 0)) into v_max;
  if v_max > 0 then
    perform setval(pg_get_serial_sequence('admin.guardian_decisions', 'id'), v_max);
  end if;

  insert into admin.guardian_decisions (scan_id, domain, owner_ref, by_ref, is_scam, note, connected,
                                        thresholds_version, ai_score, ai_status, created_at)
  select v.scan_id, v.domain, x.owner_ref, x.by_ref, v.value = 'not_safe', admin.mask_note(v.notes),
         v.owner_id = v.by_device_id
           or exists (select 1 from public.family_links f
                       where f.protected_id = v.owner_id and f.guardian_id = v.by_device_id),
         (select version from admin.public_config), s.score, s.status::text, v.decided_at
    from public.verdicts v
    cross join lateral (select admin.owner_ref(v.owner_id) as owner_ref,
                               admin.owner_ref(v.by_device_id) as by_ref) x
    left join public.scans s on s.id = v.scan_id
   where v.scan_id is not null
     and v.decided_at > p_cutoff
     -- A pair that unlinked (labels deleted, K11) stays forgotten, also when it linked again later.
     and (v.owner_id = v.by_device_id
          or exists (select 1 from public.family_links f
                      where f.protected_id = v.owner_id and f.guardian_id = v.by_device_id
                        and f.created_at <= v.decided_at))
     and not admin._forgotten(x.owner_ref, x.by_ref, v.decided_at)
     and not exists (
       select 1 from admin.guardian_decisions g
         left join admin.scan_archive a on a.scan_id = g.scan_id
        where g.owner_ref = x.owner_ref and g.by_ref = x.by_ref and g.domain = v.domain
          and g.is_scam = (v.value = 'not_safe')
          and (g.scan_id = v.scan_id
               or coalesce(a.host, a.domain) || a.url_path = substring(v.url from '^[A-Za-z]+://(.*)$')));
end $$;
revoke all on function admin._guardian_decisions_backfill(timestamptz)
  from public, anon, authenticated, service_role, shoo_api, shoo_admin, shoo_ai;

select admin._guardian_decisions_backfill('2026-11-08 16:13:18+00');

