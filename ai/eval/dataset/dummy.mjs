// Deterministic generator of LOCAL dummy data for the layer 5 pipeline (plan fase-09). Emits one SQL
// transaction that fills public.devices / family_links / scans / verdicts / blocklist_entries, so the
// backend's own triggers fill admin.* and the admin.ai_dataset view, exactly like prod.
// Only *.shoo-dummy.test domains, plus sites.google.com as the shared-host case.
// Run through seed-dummy.sh (it refuses a non-local database). Same seed -> same SQL.
import { readFileSync } from "node:fs";

const FAMILIES = 6;
const SHARED_DOMAIN = "sites.google.com";

// One signal per row of the real contract (id, layer 1-4, weight, labels). Weights are fixed per id.
const SIGNALS = {
    lookalike_host: [1, 20, "Host looks like a known brand", "Alamat mirip brand terkenal"],
    suspicious_tld: [1, 10, "Unusual domain ending", "Akhiran domain tidak umum"],
    brand_plus_keyword: [2, 15, "Brand name + extra word", "Nama brand + kata tambahan"],
    keyword_stuffing: [2, 10, "Many scam keywords in the address", "Banyak kata penipuan di alamat"],
    new_domain: [3, 30, "Domain is only days old", "Domain baru berumur beberapa hari"],
    asks_pin: [3, 25, "Form asks for m-banking PIN", "Form meminta PIN m-banking"],
    asks_otp: [3, 20, "Form asks for an OTP code", "Form meminta kode OTP"],
    unreasonable_request: [4, 22, "Page asks for something a real site would not", "Halaman meminta hal yang tidak wajar"],
    urgency_pressure: [4, 12, "Page pushes you to act now", "Halaman menekan untuk segera bertindak"],
};

const TEMPLATES = {
    strongA: ["new_domain", "asks_pin", "unreasonable_request", "brand_plus_keyword"], // 92, the contracts fixture
    strongB: ["new_domain", "asks_otp", "urgency_pressure", "lookalike_host"], // 82
    strongC: ["new_domain", "asks_pin", "lookalike_host", "suspicious_tld"], // 85
    mid: ["new_domain", "asks_otp", "brand_plus_keyword", "keyword_stuffing"], // 75
    weakA: ["new_domain", "suspicious_tld"], // 40
    weakB: ["new_domain", "urgency_pressure"], // 42
    mild1: ["suspicious_tld", "keyword_stuffing"], // 20
    mild2: ["brand_plus_keyword", "keyword_stuffing", "suspicious_tld"], // 35
    mild3: ["lookalike_host", "brand_plus_keyword", "keyword_stuffing"], // 45
    odd: ["lookalike_host", "brand_plus_keyword", "asks_otp"], // 55
    ambA: ["asks_pin", "suspicious_tld"], // 35
    ambB: ["asks_otp", "brand_plus_keyword", "keyword_stuffing"], // 45
    ambC: ["new_domain", "keyword_stuffing", "suspicious_tld"], // 50
    shared: ["asks_pin", "unreasonable_request", "urgency_pressure"], // 59
};

// domain, families that say not_safe, families that say safe, signal template, domain age in days [min, max]
const PLAN = [
    ...[
        ["scam-01", 5, 0, "strongA"], ["scam-02", 4, 0, "strongA"], ["scam-03", 4, 0, "strongB"], ["scam-04", 3, 0, "strongC"],
        ["scam-05", 3, 0, "mid"], ["scam-06", 2, 0, "strongB"], ["scam-07", 2, 0, "weakA"], ["scam-08", 2, 0, "weakB"],
    ].map(([n, nN, nY, t]) => ({ domain: `${n}.shoo-dummy.test`, nN, nY, t, age: [2, 40] })),
    ...[
        ["legit-01", 0, 2, "mild1"], ["legit-02", 0, 2, "mild1"], ["legit-03", 0, 2, "mild2"], ["legit-04", 0, 2, "mild3"],
        ["legit-05", 2, 2, "odd"], // wrongly blocked and disputed: conflicting verdicts
    ].map(([n, nN, nY, t]) => ({ domain: `${n}.shoo-dummy.test`, nN, nY, t, age: [730, 2900] })),
    ...[
        ["maybe-01", 1, 1, "ambA", [100, 400]], ["maybe-02", 1, 1, "ambB", [100, 400]], ["maybe-03", 1, 1, "ambC", [15, 60]],
    ].map(([n, nN, nY, t, age]) => ({ domain: `${n}.shoo-dummy.test`, nN, nY, t, age })),
    { domain: SHARED_DOMAIN, nN: 2, nY: 0, t: "shared", age: [6500, 7500], path: "/view/dummy-promo" },
];

function mulberry32(seed) {
    let a = seed >>> 0;
    return () => {
        a = (a + 0x6d2b79f5) >>> 0;
        let t = a;
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

function signalJson(id) {
    const [layer, weight, en, idn] = SIGNALS[id];
    return { id, layer, weight, label: { en, id: idn }, labelSimple: { en, id: idn } };
}

function sharedHostsSql() {
    const file = JSON.parse(readFileSync(new URL("../../data/shared-hosts.json", import.meta.url), "utf8"));
    return `select admin.shared_hosts_set(array[${file.hosts.map(q).join(", ")}]::text[], 'imelda-dummy', 'local dummy data');`;
}

export function buildDummySql({ seed = 1 } = {}) {
    const rand = mulberry32(seed);
    const int = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));
    const out = [];
    const push = (s) => out.push(s);

    push("-- Generated by ai/eval/dataset/dummy.mjs. LOCAL DATABASE ONLY.");
    push("begin;");
    // Idempotent: remove what an earlier run created. Deleting devices cascades to scans, verdicts and
    // family_links, and the device-delete trigger queues label_forget rows, which would hide the labels
    // of the next insert (same transaction timestamp), so those are removed again afterwards.
    push(`delete from admin.domain_review where domain like '%.shoo-dummy.test' or domain = ${q(SHARED_DOMAIN)};`);
    push(`delete from public.blocklist_entries where domain like '%.shoo-dummy.test' or domain = ${q(SHARED_DOMAIN)};`);
    push("delete from public.devices where id like 'dummy\\_%';");
    push(`delete from admin.domain_labels where domain like '%.shoo-dummy.test' or domain = ${q(SHARED_DOMAIN)};`);
    push(`delete from admin.scan_archive where domain like '%.shoo-dummy.test' or domain = ${q(SHARED_DOMAIN)};`);
    push(`delete from admin.domain_intel where domain like '%.shoo-dummy.test' or domain = ${q(SHARED_DOMAIN)};`);
    push(`delete from admin.domain_intel_label where domain like '%.shoo-dummy.test' or domain = ${q(SHARED_DOMAIN)};`);
    push(`delete from admin.domain_dirty where domain like '%.shoo-dummy.test' or domain = ${q(SHARED_DOMAIN)};`);
    for (let i = 1; i <= FAMILIES; i++) {
        push(`delete from admin.label_forget where owner_ref in (admin.owner_ref('dummy_g${i}'), admin.owner_ref('dummy_p${i}'));`);
    }

    for (let i = 1; i <= FAMILIES; i++) {
        for (const [prefix, mode] of [["g", "guardian"], ["p", "protected"]]) {
            const id = `dummy_${prefix}${i}`;
            push(
                `insert into public.devices (id, name, mode, avatar_id, language, token_hash) values ` +
                    `(${q(id)}, ${q(`Dummy ${prefix.toUpperCase()}${i}`)}, '${mode}', 'avatar_0${i}', 'id', extensions.digest(${q(`shoo_local_${id}`)}, 'sha256'));`,
            );
        }
        push(`insert into public.family_links (protected_id, guardian_id) values ('dummy_p${i}', 'dummy_g${i}');`);
    }

    let scanNo = 0;
    for (const item of PLAN) {
        const start = int(0, FAMILIES - 1);
        const hoursAgo = int(24, 300);
        const ageDays = int(item.age[0], item.age[1]);
        const verdicts = [];
        for (let j = 0; j < item.nN + item.nY; j++) verdicts.push({ fam: ((start + j) % FAMILIES) + 1, value: j < item.nN ? "not_safe" : "safe" });

        for (const v of verdicts) {
            scanNo += 1;
            const ids = [...TEMPLATES[item.t]];
            if (ids.length > 2 && rand() < 0.25) ids.splice(int(1, ids.length - 1), 1); // one family saw one signal less
            const signals = ids.map(signalJson);
            const score = Math.min(100, Math.max(30, signals.reduce((n, s) => n + s.weight, 0)));
            const status = score >= 80 ? "blocked" : "warning";
            const scanId = `dummy-scan-${String(scanNo).padStart(3, "0")}`;
            const detectedMin = hoursAgo * 60 + int(0, 600);
            const decidedMin = detectedMin - int(10, 120);
            const url = `https://${item.domain}${item.path ?? "/login?ref=wa"}`;
            push(
                `insert into public.scans (id, owner_id, url, domain, page_title, score, status, signals, detected_at, rdap_registered_at) values ` +
                    `(${q(scanId)}, 'dummy_p${v.fam}', ${q(url)}, ${q(item.domain)}, ${q(`Dummy page ${item.domain}`)}, ${score}, '${status}', ` +
                    `${q(JSON.stringify(signals))}::jsonb, now() - interval '${detectedMin} minutes', current_date - ${ageDays});`,
            );
            push(
                `insert into public.verdicts (owner_id, domain, value, scan_id, by_device_id, by_name, decided_at, global_eligible) values ` +
                    `('dummy_p${v.fam}', ${q(item.domain)}, '${v.value}', ${q(scanId)}, 'dummy_g${v.fam}', ${q(`Dummy G${v.fam}`)}, ` +
                    `now() - interval '${decidedMin} minutes', ${v.value === "not_safe"});`,
            );
        }
        if (item.nN >= 2) {
            push(
                `insert into public.blocklist_entries (domain, families, first_seen_at) values (${q(item.domain)}, ${item.nN}, now() - interval '${hoursAgo} hours') ` +
                    `on conflict (domain) do update set families = excluded.families;`,
            );
        }
    }

    push(sharedHostsSql());
    push("select admin.run_analysis('manual', 'imelda-dummy');");
    push("alter role shoo_ai password 'shoo_ai_local';"); // local only, like shoo_api / shoo_admin in seed.sql
    push("commit;");
    return out.join("\n") + "\n";
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
    const seedArg = process.argv.indexOf("--seed");
    process.stdout.write(buildDummySql({ seed: seedArg > 0 ? Number(process.argv[seedArg + 1]) : 1 }));
}
