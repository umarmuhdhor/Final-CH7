// Turns public_suffix_list.dat into Resources/psl.js (ES module imported by background.js).
// Usage: node build-psl.mjs <public_suffix_list.dat>   — normally via update-psl.sh.
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
    console.error("usage: node build-psl.mjs <public_suffix_list.dat>");
    process.exit(1);
}

const text = readFileSync(input, "utf8");
const version = text.match(/^\/\/ VERSION: (.+)$/m)?.[1] ?? "unknown";

// location.hostname is punycode, so rules must be too ("公司.cn" → "xn--55qx5d.cn").
function toAscii(rule) {
    const prefix = rule.match(/^(!|\*\.)/)?.[0] ?? "";
    const ascii = domainToASCII(rule.slice(prefix.length));
    return ascii ? prefix + ascii : null;
}

const rules = new Set();
for (const line of text.split("\n")) {
    const rule = line.trim().split(/\s/)[0];
    if (!rule || rule.startsWith("//")) continue;
    const ascii = toAscii(rule);
    if (ascii) rules.add(ascii);
}

const out = fileURLToPath(new URL("../Resources/psl.js", import.meta.url));
writeFileSync(
    out,
    `// GENERATED by ios/ShooExtension/scripts/update-psl.sh — DO NOT EDIT.\n` +
        `// Public Suffix List (https://publicsuffix.org), MPL 2.0. ICANN + private sections.\n` +
        `export const PSL_VERSION = ${JSON.stringify(version)};\n` +
        `export const PSL_RULES = ${JSON.stringify([...rules].join("\n"))};\n`,
);
console.log(`psl.js: ${rules.size} rules, version ${version}`);
